export function getRegionCoordinates(province: string, city: string, district: string): { lat: number; lon: number } {
  if (COORD_LOOKUP[district]) {
    return COORD_LOOKUP[district];
  }
  if (PROVINCE_FALLBACK[province]) {
    // 增加微小抖动避免完全重叠
    const base = PROVINCE_FALLBACK[province];
    const hash = (city.length * 31 + district.length * 17) % 100;
    return {
      lat: base.lat + (hash / 100 - 0.5) * 1.5,
      lon: base.lon + ((hash * 7) % 100 / 100 - 0.5) * 1.5,
    };
  }
  return { lat: 35.0, lon: 105.0 }; // 中国几何中心
}
